export function getArcById(arcId: string | null | undefined): HistoryArc | null {
  if (!arcId) return null;
  return HISTORY_ARCS.find(arc => arc.id === arcId) ?? null;
}

export function getArcFamily(arc: HistoryArc): ArcFamily | null {
  return ARC_FAMILIES.find(family => family.kinds.includes(arc.kind)) ?? null;
}

export function getArcFieldsForNode(nodeId: string): Pick<TimelineNodeStub, 'arcIds' | 'arcRoles'> {
  const arcIds: string[] = [];
  const arcRoles: Record<string, HistoryArcRole> = {};

  for (const arc of HISTORY_ARCS) {
    if (!arc.nodeIds.includes(nodeId)) continue;

    arcIds.push(arc.id);
    arcRoles[arc.id] =
      ARC_ROLE_OVERRIDES[arc.id]?.[nodeId] ??
      (arc.startNodeIds.includes(nodeId) ? 'ignition' : 'milestone');
  }

  return {
    arcIds: arcIds.length > 0 ? arcIds : undefined,
    arcRoles: Object.keys(arcRoles).length > 0 ? arcRoles : undefined,
  };
}

export function applyArcMemberships<T extends TimelineNodeStub>(nodes: T[]): T[] {
  return nodes.map(node => ({
    ...node,
    ...getArcFieldsForNode(node.id),
  }));
}

export function getArcNodes(arc: HistoryArc | null, nodes: TimelineNodeStub[]): TimelineNodeStub[] {
  if (!arc) return [];
  const nodeById = new Map(nodes.map(node => [node.id, node]));
  return arc.nodeIds.map(nodeId => nodeById.get(nodeId)).filter((node): node is TimelineNodeStub => Boolean(node));
}

export function getRelatedArcs(arc: HistoryArc | null): HistoryArc[] {
  if (!arc?.relatedArcIds) return [];
  return arc.relatedArcIds.map(getArcById).filter((relatedArc): relatedArc is HistoryArc => Boolean(relatedArc));
}

export function getPhilosophyLessonTemplate(nodeId: string | undefined): PhilosophyLessonTemplate | null {
  if (!nodeId) return null;
  return PHILOSOPHY_LESSON_TEMPLATES[nodeId] ?? null;
}
